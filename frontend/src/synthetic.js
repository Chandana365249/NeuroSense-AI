// Synthetic test signal for trying the upload path without the licensed DEAP dataset.
// It is generated noise plus sine rhythms: NOT recorded EEG, NOT DEAP data, and it says so in the file itself.

export const SYNTHETIC_FILE_NAME = 'neurosense_synthetic_test_signal_NOT_REAL_EEG.json';
export const SYNTHETIC_NOTE = 'Synthetic test signal generated by NeuroSense AI: random noise plus sine rhythms. '
  + 'It is not recorded EEG, not DEAP data, and any result on it is meaningless as a valence estimate.';

/** Small deterministic PRNG (mulberry32) so the same seed always gives the same file. */
function prng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 32 channels x (seconds x rate) samples in microvolt-like units, rounded to 3 decimals. */
export function makeSyntheticSignal({ seconds = 60, channels = 32, rate = 128, seed = 20261020 } = {}) {
  const rand = prng(seed);
  const n = Math.round(seconds * rate);
  const signal = [];
  for (let c = 0; c < channels; c += 1) {
    const alphaHz = 8.5 + 3 * rand(); const alphaAmp = 4 + 6 * rand(); const alphaPhase = 2 * Math.PI * rand();
    const betaHz = 15 + 10 * rand(); const betaAmp = 1 + 2 * rand(); const betaPhase = 2 * Math.PI * rand();
    const row = new Array(n);
    for (let i = 0; i < n; i += 1) {
      const t = i / rate;
      const noise = (rand() + rand() + rand() + rand() - 2) * 6; // approximately normal, SD about 3.5
      row[i] = Math.round((noise + alphaAmp * Math.sin(2 * Math.PI * alphaHz * t + alphaPhase)
        + betaAmp * Math.sin(2 * Math.PI * betaHz * t + betaPhase)) * 1000) / 1000;
    }
    signal.push(row);
  }
  return { synthetic_test_fixture: true, note: SYNTHETIC_NOTE, sampling_rate: rate, includes_baseline: false, signal };
}
